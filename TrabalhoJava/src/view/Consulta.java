    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = tabelaCasos.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(null, "Por favor, selecione um caso clínico na tabela primeiro.");
            return; 
        }
        Object objTitulo = tabelaCasos.getValueAt(linhaSelecionada, 1);
        String tituloSelecionado = objTitulo != null ? objTitulo.toString() : "";
    
        Object objDescricao = tabelaCasos.getValueAt(linhaSelecionada, 2);
        String descricaoAtual = objDescricao != null ? objDescricao.toString() : "";
    
        Object objPergunta = tabelaCasos.getValueAt(linhaSelecionada, 3);
        String perguntaAtual = objPergunta != null ? objPergunta.toString() : "";
        String novaPergunta = JOptionPane.showInputDialog(null, "Edite a descrição:", perguntaAtual);
        if (novaPergunta != null) {
        
        CasoClinicoDao dao = new CasoClinicoDao();
            try {
                dao.perguntaAdd(tituloSelecionado, descricaoAtual,novaPergunta);
                JOptionPane.showMessageDialog(null, "Pergunta atualizada!");
                listarCasosClinicos();
            } catch (SQLException ex) {
                System.getLogger(Consulta.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
            }else{
            JOptionPane.showMessageDialog(null, "Erro ao atualizar no banco de dados.");
        }
        
    }//GEN-LAST:event_jButton3ActionPerformed
    
    public void listarLeft() throws SQLException{
        DefaultTableModel modelo = (DefaultTableModel) tabelaCasos.getModel();
        modelo.setNumRows(0); 

    
        CasoClinicoDao dao = new CasoClinicoDao();
        List<CasoClinico> lista = dao.listarLeft();

        for (CasoClinico c : lista){
            modelo.addRow(new Object[]{
                c.getProfessor() != null ? c.getProfessor().getNome() : "Sem Professor",
                c.getTitulo(),
                c.getDescricao(),
                c.getPergunta() != null ? c.getPergunta().getEnuciado() : "Sem pergunta"
            });
        }
    }
    
    public void listarCasosClinicos() throws SQLException{
        DefaultTableModel modelo = (DefaultTableModel) tabelaCasos.getModel();
        modelo.setNumRows(0); 

    
        CasoClinicoDao dao = new CasoClinicoDao();
        List<CasoClinico> lista = dao.listarTodos();

        for (CasoClinico c : lista){
            modelo.addRow(new Object[]{
                c.getProfessor().getNome(),
                c.getTitulo(),
                c.getDescricao(),
                c.getPergunta().getEnuciado()
            });
        }
        
    }
    
    
