    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = tabelaCasos.getSelectedRow();
        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(null, "Por favor, selecione um caso clínico na tabela primeiro.");
            return; 
        }
        String tituloSelecionado = tabelaCasos.getValueAt(linhaSelecionada, 1).toString();
        String descricaoAtual = tabelaCasos.getValueAt(linhaSelecionada, 2).toString();
        String novaDescricao = JOptionPane.showInputDialog(null, "Edite a descrição:", descricaoAtual);
        if (novaDescricao != null && !novaDescricao.trim().isEmpty()) {
        
        CasoClinicoDao dao = new CasoClinicoDao();
            try {
                dao.editarDescricao(tituloSelecionado, novaDescricao);
                JOptionPane.showMessageDialog(null, "Descrição atualizada!");
                listarCasosClinicos();
            } catch (SQLException ex) {
                System.getLogger(Consulta.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
            }else{
            JOptionPane.showMessageDialog(null, "Erro ao atualizar no banco de dados.");
        }
        
        

    
    }//GEN-LAST:event_jButton1ActionPerformed

